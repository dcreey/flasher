    func testEveryDocumentedMistakeIsFlagged() {
        let missed = Self.mistakes.filter { !MoodCheckerCoverageTests.flagged($0.text) }.map { "\($0.section): \($0.text)" }
        XCTAssertEqual(missed, [], "\(missed.count) of \(Self.mistakes.count) mistakes not flagged")
    }

    func testCorrectSentencesAreNotFlagged() {
        let wrong = Self.correct.compactMap { text -> String? in
            let errors = SpanishChecker.check(text).filter { $0.kind == .verb || $0.kind == .grammar }
            return errors.isEmpty ? nil : "\(text) <<< \(errors.map(\.message).joined(separator: " | "))"
        }
        XCTAssertEqual(wrong, [], "\(wrong.count) correct sentences flagged")
    }
